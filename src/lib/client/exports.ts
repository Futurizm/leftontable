import type { AnalysisSession, EngineResult } from "../types";
import { usd } from "../format";

const pad = (n: number) => String(n).padStart(2, "0");
const icsDate = (d: Date) => `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}`;
const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/;/g, "\\;").replace(/,/g, "\\,").replace(/\n/g, "\\n");

function parseDate(s: string | null | undefined): Date | null {
  if (!s) return null;
  const t = Date.parse(s.replace(/(\d)(st|nd|rd|th)/g, "$1"));
  if (Number.isNaN(t)) return null;
  const d = new Date(t);
  return d.getTime() > Date.now() - 864e5 ? d : null;
}

export function buildIcs(session: AnalysisSession, result: EngineResult): string {
  const live = result.opportunities.filter((o) => !session.profile.dismissed.includes(o.key));
  const events: { date: Date; title: string; desc: string }[] = [];
  const tomorrow = new Date(Date.now() + 864e5);
  const now = live.filter((o) => o.deadline?.startsWith("Any time"));
  if (now.length) {
    events.push({
      date: tomorrow,
      title: `Claim ${usd(now.reduce((s, o) => s + o.annualValue, 0))}/yr: ${now.map((o) => o.title).join(", ")}`,
      desc: now.map((o) => `${o.title} (${usd(o.annualValue)}/yr)\n- ${o.steps.join("\n- ")}`).join("\n\n"),
    });
  }
  const oeEnd = parseDate(session.benefits.openEnrollment?.end);
  const oeItems = live.filter((o) => o.deadline?.startsWith("Open enrollment") || o.deadline === "Next open enrollment");
  if (oeItems.length) {
    const d = oeEnd ? new Date(oeEnd.getTime() - 2 * 864e5) : tomorrow;
    events.push({
      date: d,
      title: `Open enrollment: lock in ${usd(oeItems.reduce((s, o) => s + o.annualValue, 0))}/yr`,
      desc: oeItems.map((o) => `${o.title} (${usd(o.annualValue)}/yr)\n- ${o.steps.join("\n- ")}`).join("\n\n"),
    });
  }
  if (live.some((o) => o.key === "fsa-tax")) {
    events.push({ date: new Date(new Date().getFullYear(), 11, 1), title: "FSA check: spend or lose your balance by Dec 31", desc: "Use remaining Health FSA dollars: glasses, contacts, dental work, prescriptions, first-aid supplies." });
  }
  const stamp = new Date().toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  const body = events
    .map((e, i) =>
      [
        "BEGIN:VEVENT",
        `UID:leftontable-${session.id}-${i}@leftontable.app`,
        `DTSTAMP:${stamp}`,
        `DTSTART;VALUE=DATE:${icsDate(e.date)}`,
        `DTEND;VALUE=DATE:${icsDate(new Date(e.date.getTime() + 864e5))}`,
        `SUMMARY:${esc(e.title)}`,
        `DESCRIPTION:${esc(e.desc)}`,
        "BEGIN:VALARM", "TRIGGER:-PT15H", "ACTION:DISPLAY", `DESCRIPTION:${esc(e.title)}`, "END:VALARM",
        "END:VEVENT",
      ].join("\r\n"),
    )
    .join("\r\n");
  return ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//LeftOnTable//EN", "CALSCALE:GREGORIAN", body, "END:VCALENDAR"].join("\r\n");
}

export function buildPlanText(session: AnalysisSession, result: EngineResult): string {
  const live = result.opportunities.filter((o) => !session.profile.dismissed.includes(o.key));
  const head = `My benefits action plan — ${session.benefits.employerName ?? "my employer"} (${session.benefits.planYear ?? "2026"})\nEstimated money left on the table: ${usd(result.total)}/yr\n`;
  const items = live.map(
    (o, i) => `\n${i + 1}. ${o.title} — ${usd(o.annualValue)}/yr${o.kind === "optional" ? " (optional)" : ""}\n${o.steps.map((s) => `   • ${s}`).join("\n")}${o.evidence ? `\n   Source: "${o.evidence.quote}"${o.evidence.page ? ` (p. ${o.evidence.page})` : ""}` : ""}${o.deadline ? `\n   When: ${o.deadline}` : ""}`,
  );
  return head + items.join("\n") + "\n\nGenerated by LeftOnTable. Estimates only — confirm with your plan administrator.";
}

export function buildHrEmail(session: AnalysisSession, result: EngineResult): string {
  const live = result.opportunities.filter((o) => !session.profile.dismissed.includes(o.key));
  const qs = live.slice(0, 6).map((o) => {
    if (o.key === "401k-match") return "- Can you confirm the 401(k) match formula and whether there is an annual true-up?";
    if (o.key === "hsa-employer") return "- How and when is the employer HSA contribution deposited? Do I need to contribute myself to receive it?";
    if (o.key === "commuter") return "- How do I enroll in the commuter benefit, and when does the employer subsidy start?";
    if (o.key === "dcfsa") return "- Can I enroll in the Dependent Care FSA, and what documentation do you need from my provider?";
    if (o.key === "plan-switch") return "- When does open enrollment close, and can I switch medical plans for next year?";
    if (o.key === "fsa-tax" || o.key === "hsa-tax") return "- How do I change my FSA/HSA election, and when does it take effect?";
    return `- How do I claim the ${o.title}?`;
  });
  return `Subject: Questions about my benefits\n\nHi,\n\nI was reviewing the ${session.benefits.planYear ?? "2026"} benefits guide and want to make sure I'm using everything available to me. Could you help with the following?\n\n${qs.join("\n")}\n\nThank you!\n`;
}

export function download(name: string, content: string, type: string) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
